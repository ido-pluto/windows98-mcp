import { readFile, writeFile } from "node:fs/promises";

const manifest = JSON.parse(await readFile("package.json", "utf8"));
if (typeof manifest.name !== "string" || typeof manifest.version !== "string") {
  throw new Error("package.json must contain string name and version fields");
}

const source = `// Generated by scripts/write-package-info.mjs during npm run build.\nexport const PACKAGE_NAME = ${JSON.stringify(manifest.name)};\nexport const PACKAGE_VERSION = ${JSON.stringify(manifest.version)};\n`;
await writeFile("src/shared/package-info.ts", source, "utf8");
